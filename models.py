# STAGE 3: JD EXTRACTION SCHEMAS
# ==========================================

class RequirementItem(BaseModel):
    requirement: str
    category: str = Field(
        default="hard_skill",
        description="hard_skill | soft_skill | tool | certification | experience_years | education"
    )
    keywords: List[str] = Field(default_factory=list, description="Keywords including acronyms and full terms")


class CompanyContext(BaseModel):
    industry: str = ""
    size: str = ""
    notes: str = ""


class JDExtraction(BaseModel):
    job_title: str = ""
    company: str = ""
    seniority_level: str = ""
    employment_type: str = ""
    must_have_requirements: List[RequirementItem] = Field(default_factory=list)
    nice_to_have_requirements: List[str] = Field(default_factory=list)
    core_responsibilities: List[str] = Field(default_factory=list)
    keywords_for_ats: List[str] = Field(default_factory=list)
    company_context: CompanyContext = Field(default_factory=CompanyContext)


# ==========================================
# STAGE 4: GAP & MATCH ANALYSIS SCHEMAS
# ==========================================

class GapAnalysisResult(BaseModel):
    matched_keywords: List[str] = Field(default_factory=list)
    missing_keywords: List[str] = Field(default_factory=list)
    keyword_coverage_pct: float = 0.0
    matched_must_haves: List[RequirementItem] = Field(default_factory=list)
    unmatched_must_haves: List[RequirementItem] = Field(default_factory=list)
    must_have_coverage_pct: float = 0.0
    unmatched_nice_to_haves: List[str] = Field(default_factory=list)


# ==========================================
# STAGE 5: TAILORED RESUME SCHEMAS
# ==========================================

class TailoredBullet(BaseModel):
    source_bullet_id: str = Field(description="Must point to a valid bullet ID in MasterProfile")
    tailored_text: str = Field(description="Tailored phrasing mirroring JD language")


class TailoredExperience(BaseModel):
    id: str  # we_1
    company: str
    title: str
    location: str
    start_date: Optional[str] = None
    end_date: Optional[str] = None
    is_current: bool = False
    bullets: List[TailoredBullet] = Field(default_factory=list)


class TailoredResume(BaseModel):
    job_id_ref: str = ""
    target_job_title: str = ""
    target_company: str = ""
    generated_at: str = ""
    summary: str = ""
    selected_experience: List[TailoredExperience] = Field(default_factory=list)
    selected_education: List[Education] = Field(default_factory=list)
    selected_skills: SkillCategories = Field(default_factory=SkillCategories)
    selected_certifications: List[str] = Field(default_factory=list)
    selected_projects: List[ProjectItem] = Field(default_factory=list)
    selected_achievements: List[str] = Field(default_factory=list)
    unmatched_must_haves_notes: List[str] = Field(
        default_factory=list,
        description="Must-haves from JD that Master Profile does not support - for candidate awareness"
    )


