class GroundingIssue(BaseModel):
    source_id: str
    tailored_text: str
    reason: str
    severity: str = Field(default="error", description="error (unsupported fact) | warning (stretch)")


class GroundingCheckResult(BaseModel):
    passed: bool = True
    unsupported_claims: List[GroundingIssue] = Field(default_factory=list)


# ==========================================
# STAGE 7: ATS FORMAT VALIDATION SCHEMAS
# ==========================================

class ATSValidationIssue(BaseModel):
    rule: str
    message: str
    severity: str = Field(default="error", description="error | warning")


class ATSValidationResult(BaseModel):
    passed: bool = True
    score: int = 100
    issues: List[ATSValidationIssue] = Field(default_factory=list)


